-- Schema of the production project as of 2026-10-29 (created from the dashboard, without migrations).

create table public.bookings (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  start_date date,
  end_date date,
  name text
);

create table public.notes (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  note text,
  author text
);

alter table public.bookings enable row level security;
alter table public.notes enable row level security;

-- The site has no login: anyone can read, add and delete bookings.
create policy "Bookings policy" on public.bookings
  for all
  using (true);

grant all on public.bookings to anon, authenticated;
grant all on public.notes to anon, authenticated;
